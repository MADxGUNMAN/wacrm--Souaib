// Regenerates the on-disk starter-library seed migrations from the live table.
//
// Migrations 067 and 068 were originally applied straight to the project through
// the Supabase migration API, so the repo never got a copy. Rather than
// hand-transcribing 40 KB of SQL, this reads the rows back out and emits
// equivalent idempotent upserts. Run it again any time the library is edited in
// the super-admin panel and you want the change tracked in git:
//
//   node scripts/generate-library-seed.mjs
//
// Strings are emitted dollar-quoted ($t$...$t$) rather than as E'' literals.
// Template bodies are full of newlines, quotes and emoji, and dollar quoting
// passes all three through untouched — one less escaping bug to chase.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();

// Minimal .env.local reader. dotenv is a dev dependency here, but a one-off
// script has no business caring which loader the app happens to use.
const env = {};
for (const line of readFileSync(join(root, '.env.local'), 'utf8').split(/\r?\n/)) {
  const match = /^([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line.trim());
  if (match) env[match[1]] = match[2].replace(/^["']|["']$/g, '');
}

const url = env.NEXT_PUBLIC_SUPABASE_URL;
const key = env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) throw new Error('NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set in .env.local');

async function table(name, select) {
  const res = await fetch(`${url}/rest/v1/${name}?select=${select}&order=position.asc`, {
    headers: { apikey: key, Authorization: `Bearer ${key}` },
  });
  if (!res.ok) throw new Error(`${name}: ${res.status} ${await res.text()}`);
  return res.json();
}

// Dollar-quoted literal, or a bare NULL so nullable columns stay nullable
// instead of becoming empty strings.
const lit = (value) => (value === null || value === undefined ? 'NULL' : `$t$${value}$t$`);
const json = (value) => (value === null || value === undefined ? 'NULL' : `$t$${JSON.stringify(value)}$t$::jsonb`);
const arr = (value) => `ARRAY[${(value ?? []).map((tag) => `$t$${tag}$t$`).join(',')}]::text[]`;

const categories = await table('template_library_categories', 'id,slug,name,emoji,position');
const templates = await table(
  'template_library_templates',
  'category_id,slug,title,description,emoji,meta_category,template_type,language,header_type,header_content,body_text,footer_text,buttons,sample_values,tags,position',
);

const slugById = new Map(categories.map((c) => [c.id, c.slug]));

// The original split, kept so the two on-disk files line up with the two
// versions already recorded in the project's migration history.
const PART_1 = ['ecommerce', 'education', 'healthcare', 'real-estate', 'travel', 'automotive', 'bfsi', 'logistics'];

const HEADER = `-- Starter templates, part %PART% of 2. Generated by scripts/generate-library-seed.mjs.
--
-- Written to PASS META REVIEW, which is stricter about wording than about
-- structure. Two rules drive every choice here:
--
--   * UTILITY must be transactional — about an order, account or booking the
--     customer already has. One promotional sentence in a utility template gets
--     it reclassified as marketing, which changes what it costs to send.
--   * Every variable ships with a REALISTIC sample value. Vague samples
--     ("test", "abc") are one of the most common rejection reasons, so the
--     library never leaves an operator to invent them.
--
-- Variables are contiguous from {{1}} — Meta rejects gaps — and footers carry no
-- variables, which Meta also forbids.
--
-- Idempotent on slug, so re-running refreshes the shipped copy without
-- duplicating rows and without touching templates an operator added themselves.
`;

function emit(part, rows) {
  const values = rows
    .map((t) => {
      const category = slugById.get(t.category_id);
      return `(${lit(category)}, ${lit(t.slug)}, ${lit(t.title)}, ${lit(t.description)}, ${lit(t.emoji)},
 ${lit(t.meta_category)}, ${lit(t.template_type)}, ${lit(t.language)}, ${lit(t.header_type)}, ${lit(t.header_content)},
 ${lit(t.body_text)},
 ${lit(t.footer_text)}, ${json(t.buttons)}, ${json(t.sample_values)}, ${arr(t.tags)}, ${t.position})`;
    })
    .join(',\n\n');

  return `${HEADER.replace('%PART%', String(part))}
INSERT INTO template_library_templates (
  category_id, slug, title, description, emoji, meta_category, template_type, language,
  header_type, header_content, body_text, footer_text, buttons, sample_values, tags, position
)
SELECT c.id, v.slug, v.title, v.description, v.emoji, v.meta_category, v.template_type, v.language,
       v.header_type, v.header_content, v.body_text, v.footer_text, v.buttons, v.sample_values,
       v.tags, v.position
FROM (VALUES

${values}

) AS v(cat_slug, slug, title, description, emoji, meta_category, template_type, language,
       header_type, header_content, body_text, footer_text, buttons, sample_values, tags, position)
JOIN template_library_categories c ON c.slug = v.cat_slug
ON CONFLICT (slug) DO UPDATE
SET title = EXCLUDED.title, description = EXCLUDED.description, emoji = EXCLUDED.emoji,
    meta_category = EXCLUDED.meta_category, template_type = EXCLUDED.template_type,
    language = EXCLUDED.language, header_type = EXCLUDED.header_type,
    header_content = EXCLUDED.header_content, body_text = EXCLUDED.body_text,
    footer_text = EXCLUDED.footer_text, buttons = EXCLUDED.buttons,
    sample_values = EXCLUDED.sample_values, tags = EXCLUDED.tags, position = EXCLUDED.position;
`;
}

// Order by category position first so the generated file reads in the same
// order the browse UI shows, not in whatever order Postgres returned rows.
const byCategory = new Map(categories.map((c, index) => [c.slug, index]));
const sorted = [...templates].sort((a, b) => {
  const left = byCategory.get(slugById.get(a.category_id)) ?? 0;
  const right = byCategory.get(slugById.get(b.category_id)) ?? 0;
  return left - right || a.position - b.position;
});

const part1 = sorted.filter((t) => PART_1.includes(slugById.get(t.category_id)));
const part2 = sorted.filter((t) => !PART_1.includes(slugById.get(t.category_id)));

writeFileSync(join(root, 'supabase/migrations/067_template_library_seed_part1.sql'), emit(1, part1));
writeFileSync(join(root, 'supabase/migrations/068_template_library_seed_part2.sql'), emit(2, part2));

console.log(`067: ${part1.length} templates`);
console.log(`068: ${part2.length} templates`);
console.log(`categories: ${categories.length}`);
